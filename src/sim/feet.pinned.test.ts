const STANCES: readonly Stance[] = ['goofy', 'regular'];
const FIELDS = ['x', 'y', 'z', 'yaw', 'pitch', 'roll'] as const;
const flat = (f: FootPose) => FIELDS.map((k) => f[k]);

describe('feet for positive inputs are pinned (ADR-30, re-recorded for ADR-32, ADR-33 and ADR-36)', () => {
  it.each(Object.keys(PINNED))('%s matches the recorded poses', (key) => {
    const { inputs, rows } = PINNED[key]!;
    const flight = computeFlight(inputs);
    const perStance = rows.length / STANCES.length;
    rows.forEach((row, n) => {
      const stance = STANCES[Math.floor(n / perStance)]!;
      const u = row[0]!;
      const pose = writeFeetIntent(newFeetPose(), inputs, u < 0 ? null : flight, Math.max(0, u), stance);
      const got = [...flat(pose.front), ...flat(pose.back)];
      got.forEach((v, j) => {
        const want = row[j + 1]!;
        // 12 significant digits were kept: a relative tolerance of 1e-10.
        expect(Math.abs(v - want)).toBeLessThanOrEqual(1e-10 * Math.max(1, Math.abs(want)));
      });
    });
  });
});
