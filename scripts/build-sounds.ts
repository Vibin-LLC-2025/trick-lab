// npm run sounds (step 18, ADR-73): builds public/sounds/ from the CC0
// recordings in assets/source/sounds/, as src/audio/soundSpec.ts says: each
// take's layers placed and mixed, leading silence cut, a high-pass at 60 Hz,
// cut to its length with a fade, levelled to its peak, and encoded as mono
// MP3. Writes public/sounds/CREDITS.md beside them. Needs ffmpeg on the PATH
// (not part of npm run verify: the files are committed, and assets:check
// enforces their budgets on the committed bytes).
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENCODING, RECORDED_KINDS, SOUND_DIR, SOUND_SOURCE, TAKES, takeFile, type Take } from '../src/audio/soundSpec';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'public', SOUND_DIR);
const ffmpeg = (args: string[]) => execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

/** The mix of a take, before levelling, as a filter graph over its inputs. */
function mixGraph(take: Take): string {
  const parts = take.layers.map(
    (l, i) => `[${i}:a]aformat=channel_layouts=mono:sample_rates=${ENCODING.rate},silenceremove=start_periods=1:start_threshold=-50dB,volume=${l.db}dB,adelay=${Math.round(l.at * 1000)},apad=whole_dur=${take.length},atrim=0:${take.length}[l${i}]`,
  );
  const inputs = take.layers.map((_, i) => `[l${i}]`).join('');
  const mix = take.layers.length > 1 ? `${inputs}amix=inputs=${take.layers.length}:normalize=0:duration=longest` : `${inputs}anull`;
  return `${parts.join(';')};${mix},highpass=f=60,atrim=0:${take.length},afade=t=out:st=${(take.length - take.fade).toFixed(3)}:d=${take.fade}[m]`;
}

function build() {
  mkdirSync(OUT, { recursive: true });
  const tmp = mkdtempSync(join(tmpdir(), 'trick-lab-sounds-'));
  const rows: string[] = [];
  try {
    for (const kind of RECORDED_KINDS) {
      TAKES[kind].forEach((take, i) => {
        const raw = join(tmp, `${kind}-${i}.wav`);
        const inputs = take.layers.flatMap((l) => ['-i', resolve(ROOT, SOUND_SOURCE.dir, l.file)]);
        ffmpeg(['-filter_complex_threads', '1', '-threads', '1', ...inputs, '-filter_complex', mixGraph(take), '-map', '[m]', '-c:a', 'pcm_s16le', raw]);
        const peak = measurePeak(raw);
        const file = takeFile(kind, i);
        const out = join(OUT, file);
        ffmpeg(['-i', raw, '-af', `volume=${(take.peak - peak).toFixed(2)}dB`, '-ac', '1', '-ar', String(ENCODING.rate), '-c:a', 'libmp3lame', '-b:a', `${ENCODING.kbps}k`, '-map_metadata', '-1', '-id3v2_version', '0', '-fflags', '+bitexact', out]);
        const bytes = statSync(out).size;
        console.log(`${SOUND_DIR}/${file}: ${(bytes / 1024).toFixed(1)} KB, ${take.length} s, peak ${take.peak} dB, from ${take.layers.map((l) => l.file).join(' + ')}`);
        rows.push(`| \`${file}\` | ${take.layers.map((l) => `\`${l.file}\``).join(', ')} |`);
      });
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  writeFileSync(join(OUT, 'CREDITS.md'), credits(rows));
  console.log(`wrote ${OUT}`);
}

/** The loudest sample of a WAV file, in dB full scale, from ffmpeg's volumedetect (which reports on stderr). */
function measurePeak(file: string): number {
  const run = spawnSync('ffmpeg', ['-hide_banner', '-i', file, '-af', 'volumedetect', '-f', 'null', '-'], { encoding: 'utf8' });
  const m = /max_volume: (-?[\d.]+) dB/.exec(run.stderr);
  if (run.status !== 0 || !m) throw new Error(`no peak measured for ${file}: ${run.stderr}`);
  return Number(m[1]);
}

function credits(rows: string[]): string {
  return `# Sound credits

Generated by \`npm run sounds\` (scripts/build-sounds.ts) from \`${SOUND_SOURCE.dir}\`; do not edit by hand.

Every file here is made from recordings in **${SOUND_SOURCE.name}** (${SOUND_SOURCE.page}), released under **${SOUND_SOURCE.licence}**: public domain, free to use and to ship, no credit owed. Fetched ${SOUND_SOURCE.fetched}. The pack's own licence text is \`${SOUND_SOURCE.dir}/License.txt\`.

Each file is trimmed, mixed (the bails layer several recordings), levelled and encoded as mono MP3 (${ENCODING.kbps} kbit/s); the takes and their levels are in \`src/audio/soundSpec.ts\`.

| File | Made from |
| --- | --- |
${rows.join('\n')}
`;
}

build();
